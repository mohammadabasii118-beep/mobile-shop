#!/usr/bin/env bash
# Writes the Caddyfile for the panel from the settings in .env:  make-caddyfile.sh ENV_FILE OUT_FILE
#   PANEL_FROM         domain (https) or http://IP
#   PANEL_ADMIN_PORT   optional: the panel's login and admin pages live only on this port ...
#   PANEL_ADMIN_PATH   ... under this secret path. The normal address then answers only what nodes and subscription
#                      links need (404 for everything else, including the login page).
set -euo pipefail
ENV_FILE="$1"; OUT="$2"
get() { grep "^$1=" "$ENV_FILE" | head -1 | cut -d= -f2- || true; }
FROM=$(get PANEL_FROM); PORT=$(get PANEL_ADMIN_PORT); APATH=$(get PANEL_ADMIN_PATH)
[ -n "$FROM" ] || { echo "PANEL_FROM missing in $ENV_FILE" >&2; exit 1; }
HEADERS='	header {
		X-Content-Type-Options nosniff
		X-Frame-Options DENY
		Referrer-Policy no-referrer
		-Server
	}'
{
  echo "# generated by install-panel.sh; do not edit (it is rewritten on every update)"
  if [ -z "$PORT" ] || [ -z "$APATH" ]; then
    printf '%s {\n%s\n\treverse_proxy panel:8000\n}\n' "$FROM" "$HEADERS"
  else
    [[ "$PORT" =~ ^[0-9]{2,5}$ ]] || { echo "bad PANEL_ADMIN_PORT" >&2; exit 1; }
    [[ "$APATH" =~ ^[A-Za-z0-9_-]{6,64}$ ]] || { echo "bad PANEL_ADMIN_PATH" >&2; exit 1; }
    ADMIN_SITE="$FROM:$PORT"
    # what nodes, agents and subscription links use on the normal address; nothing else is answered there
    printf '%s {\n%s\n' "$FROM" "$HEADERS"
    cat <<PUBLIC
	@public path /sub/* /api/node/* /api/relay/* /node/* /relay/* /node-install.sh /relay-install.sh /vtunnel.py
	handle @public {
		reverse_proxy panel:8000
	}
	handle {
		respond 404
	}
}

PUBLIC
    printf '%s {\n%s\n' "$ADMIN_SITE" "$HEADERS"
    cat <<ADMIN
	redir /$APATH /$APATH/ 308
	handle_path /$APATH/* {
		reverse_proxy panel:8000
	}
	handle {
		respond 404
	}
}
ADMIN
  fi
} > "$OUT"
